    private void hienThiLenBang(ArrayList<hangHoa> list) {
        DefaultTableModel model = (DefaultTableModel) table.getModel();
        model.setRowCount(0);

        for (hangHoa h : list) {
            String thongTinRieng = "";

            if (h instanceof dienThoai) {
                thongTinRieng = String.valueOf(((dienThoai) h).getGiaSimGhep());
            } else if (h instanceof mayTinhBang) {
                thongTinRieng = String.valueOf(((mayTinhBang) h).getKichThuocManHinh());
            }

            model.addRow(new Object[]{
                h.getTenHang(),
                h.getMaHang(),
                h.getGiaNhap(),
                h.getGiaBan(),
                thongTinRieng,
                String.format("%,.0f", h.loiNhuan())
            });
        }
    }
