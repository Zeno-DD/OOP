    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        if (danhSachHangHoa.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Danh sách trống!");
            return;
        }

        // Gọi hàm Quick Sort duy nhất
        quickSort(0, danhSachHangHoa.size() - 1);

        // Hiển thị kết quả
        hienThiLenBang(danhSachHangHoa);
        javax.swing.JOptionPane.showMessageDialog(this, "Đã sắp xếp xong!");
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:
        try {
            String input = txtTimKiem.getText().trim();
            if (input.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Khong duoc de trong");
                return;
            }
            int maCanTim = Integer.parseInt(input);
            ArrayList<hangHoa> ketQua = new ArrayList<>();
            boolean timThay = false;
            for (hangHoa hh : danhSachHangHoa) {
                if (hh.getMaHang() == maCanTim) {
                    ketQua.add(hh);
                    timThay = true;
                }
            }
            
            if (timThay) {
                hienThiLenBang(ketQua); 
            } else {
                JOptionPane.showMessageDialog(this, "Khong tim thay ma " + maCanTim);
                hienThiLenBang(danhSachHangHoa); 
            }
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ma hang phai la so nguyen");
        }
    }//GEN-LAST:event_jButton4ActionPerformed

