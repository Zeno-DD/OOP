    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {
            FileReader fr = new FileReader("hanghoa.txt");
            BufferedReader br = new BufferedReader(fr);
            
            String line = "";
            while ((line = br.readLine()) != null) {
                String[] data = line.split(", ");
                
                String loai = data[0];
                int ma = Integer.parseInt(data[1]);
                String ten = data[2];
                double giaNhap = Double.parseDouble(data[3]);
                double giaBan = Double.parseDouble(data[4]);
                
                if (loai.equalsIgnoreCase("DT")) {
                    double sim = Double.parseDouble(data[5]);
                    dienThoai dt = new dienThoai(ten, ma, giaNhap, giaBan, sim);
                    danhSachHangHoa.add(dt);
                    
                } else if (loai.equalsIgnoreCase("MTB")) {
                    double kichThuoc = Double.parseDouble(data[5]);
                    mayTinhBang mtb = new mayTinhBang(ten, ma, giaNhap, giaBan, kichThuoc);
                    danhSachHangHoa.add(mtb);
                }
            }
            
            br.close();
            fr.close();          
            JOptionPane.showMessageDialog(this, "Đọc file thành công!");
            
        }catch(Exception e){
            JOptionPane.showMessageDialog(this, "Lỗi đọc file!");
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

