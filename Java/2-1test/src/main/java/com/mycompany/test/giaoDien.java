    private void quickSort(int left, int right) {
        // Điều kiện dừng đệ quy
        if (left >= right) return;

        // B1: Chọn Pivot (Lợi nhuậ n của phần tử giữa)
        double pivot = danhSachHangHoa.get((left + right) / 2).loiNhuan();
        int i = left;
        int j = right;

        while (i <= j) {
            // Tìm phần tử bên trái <= Pivot (để đổi ra sau vì ta đang xếp GIẢM DẦN)
            while (danhSachHangHoa.get(i).loiNhuan() > pivot) {
                i++;
            }

            // Tìm phần tử bên phải >= Pivot (để đổi lên trước)
            while (danhSachHangHoa.get(j).loiNhuan() < pivot) {
                j--;
            }

            // Nếu phát hiện nghịch lý (trái nhỏ, phải lớn) -> Thực hiện SWAP ngay tại đây
            if (i <= j) {
                // --- BẮT ĐẦU ĐOẠN CODE SWAP ---
                hangHoa temp = danhSachHangHoa.get(i);
                danhSachHangHoa.set(i, danhSachHangHoa.get(j));
                danhSachHangHoa.set(j, temp);
                // --- KẾT THÚC ĐOẠN CODE SWAP ---

                i++;
                j--;
            }
        }

        // B3: Gọi đệ quy cho 2 nửa danh sách còn lại
        if (left < j) {
            quickSort(left, j);
        }
        if (i < right) {
            quickSort(i, right);
        }
    }
    
