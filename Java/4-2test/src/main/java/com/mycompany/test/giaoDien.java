    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        try{
            String input=txtTimKiem.getText().trim();
            if(input.isEmpty()){
                JOptionPane.showMessageDialog(this, "Dien vao di");
                return;
            }
            int maCanTim=Integer.parseInt(input);
            ArrayList<matHang> ketqua=new ArrayList<>();
            boolean timthay=false;
            for(matHang mh : danhSachMatHang){
                if(mh.getMaHang()==maCanTim){
                    ketqua.add(mh);
                    timthay=true;
                }
            }
            if(timthay){
                hienThiLenBang(ketqua);
            }else{
                int chon=javax.swing.JOptionPane.showConfirmDialog(this, "Không tìm thấy mặt hàng mã " + maCanTim + ". Bạn có muốn thêm mới không?", "Thông báo", javax.swing.JOptionPane.YES_NO_OPTION);               
                if (chon==javax.swing.JOptionPane.YES_OPTION) {
                    txtMaHang.setText(txtTimKiem.getText());
                    txtTimKiem.setText(null);
                }        
            }
        }catch(Exception e){
            JOptionPane.showMessageDialog(this, "So nguyen only");
        }
    }//GEN-LAST:event_jButton3ActionPerformed

