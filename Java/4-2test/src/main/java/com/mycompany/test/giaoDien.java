    private void jButton6ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton6ActionPerformed
        // TODO add your handling code here:
        try {
        java.io.FileWriter fw = new java.io.FileWriter("mathang.txt");
        java.io.BufferedWriter bw = new java.io.BufferedWriter(fw);
        for (matHang mh : danhSachMatHang) {
            String line = "";
            String loai = "";
            double thongTinRieng = 0;
            if (mh instanceof tienTe) {
                loai = "TienTe";
                thongTinRieng = ((tienTe) mh).getTyGiaChuyenDoi();
            } else if (mh instanceof trangSuc) {
                loai = "TrangSuc"; 
                thongTinRieng = ((trangSuc) mh).getGiaTheoCan();
            }
            line = loai + "," + mh.getMaHang() + "," + mh.getTenHang() + "," + mh.isDuocPhepMuaBan() + "," + thongTinRieng;
                bw.write(line);
                bw.newLine(); // Xuống dòng
            }
            bw.close();
            fw.close();
        
            javax.swing.JOptionPane.showMessageDialog(this, "Xuất file thành công!");
        
        } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Lỗi xuất file!");
        e.printStackTrace();
        }
    }//GEN-LAST:event_jButton6ActionPerformed
    private void hienThiLenBang(ArrayList<matHang> list){
        DefaultTableModel model=(DefaultTableModel) table.getModel();
        model.setRowCount(0);
        double thongTinRieng=0;
        for(matHang mh : list){
            if(mh instanceof tienTe){
                double cd = ((tienTe) mh).getTyGiaChuyenDoi();
                thongTinRieng=cd;
            }else if (mh instanceof trangSuc){
                double tc=((trangSuc) mh).getGiaTheoCan();
                thongTinRieng=tc;
            }
            model.addRow(new Object[]{
            mh.getMaHang(),
            mh.getTenHang(),
            mh.isDuocPhepMuaBan(),
            thongTinRieng
            });
        }    
    }
    
    
