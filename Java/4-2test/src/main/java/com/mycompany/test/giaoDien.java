    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try{
            FileReader fr=new FileReader("mathang.txt");
            BufferedReader br=new BufferedReader(fr);
            String line="";
            while((line=br.readLine())!=null){
                String[] data=line.split(",");
                String loai=data[0];
                int ma=Integer.parseInt(data[1]);
                String ten=data[2];
                boolean muaban=Boolean.parseBoolean(data[3]);
                double phu=Double.parseDouble(data[4]);
                if(loai.equals("TienTe")){
                    tienTe tt=new tienTe(ma, ten, muaban, phu);
                    danhSachMatHang.add(tt);
                }else{
                    trangSuc ts=new trangSuc(ma, ten, muaban, phu);
                    danhSachMatHang.add(ts);
                }
            }
            br.close();
            fr.close(); 
            JOptionPane.showMessageDialog(this, "Luu file thang cong");
        }catch(Exception e){
            JOptionPane.showMessageDialog(this, "Lỗi đọc file!");
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

