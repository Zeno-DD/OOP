    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        DefaultTableModel table1=(DefaultTableModel) table.getModel();
        //if(jRadioButton1ActionPerformed.isSelected())
        String thuocTinhCon=txtThuocTinhCon.getText();
        
        for(canBo c: danhSachCanBo){
            String giaTriRieng = "";
            if (c instanceof nhanVien){
                // Nếu là Nhân viên -> Ép kiểu sang nhanVien để lấy Ngành Đào Tạo
                giaTriRieng=((nhanVien) c).getNganhDaoTao(); 
            } 
            else if (c instanceof quanLy){
                // Nếu là Quản lý -> Ép kiểu sang quanLy để lấy Hệ số chức vụ
                // (Phải đổi số sang String để hiển thị)
                giaTriRieng=String.valueOf(((quanLy) c).getQuanLyChucVu());
            }
      
            table1.addRow(new Object[]{
                c.getHoTen(),
                c.getNamSinh(),
                c.getGioiTinh(),
                c.getDiaChi(),
                c.getHeSoLuong(),
                c.getLuongCoBan(), 
                giaTriRieng,
                c.tinhLuong()
            });
        }
    }//GEN-LAST:event_jButton3ActionPerformed

