    private void xuatFileActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_xuatFileActionPerformed
        // TODO add your handling code here:     
        //lưu file
        try{
            FileWriter fw = new FileWriter("canbo.txt");
            BufferedWriter bw = new BufferedWriter(fw);
            for (canBo c : danhSachCanBo) {
                String line = "";
                line = c.getHoTen() + ", " + c.getNamSinh() + ", " + c.getGioiTinh() + ", " + c.getDiaChi() + ", " + c.getHeSoLuong();
                if (c instanceof nhanVien) {
                    line += ", Nganh: " + ((nhanVien) c).getNganhDaoTao();
                } else if (c instanceof quanLy) {
                    line += ", He so chuc vu: " + ((quanLy) c).getQuanLyChucVu();
                }
                bw.write(line);
                bw.newLine(); 
            }
            bw.close();
            fw.close();
            JOptionPane.showMessageDialog(this, "Lưu file canbo.txt thành công!");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Lỗi lưu file!");
            e.printStackTrace();
        }
    }//GEN-LAST:event_xuatFileActionPerformed

